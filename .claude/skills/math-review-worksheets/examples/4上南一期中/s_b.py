def prot_cell(ray, base, choices=None, ex=None, sc=0.95):
    items = [("img", figs.protractor(ray, base), sc)]
    if choices:
        a, b = choices
        if ex:
            items.append(("p", ("☑", "ex"), f" {a} 度　　□ {b} 度"))
        else:
            items.append(("p", f"□ {a} 度　　□ {b} 度"))
    else:
        items.append(("p", "（　　　）度"))
    return items


