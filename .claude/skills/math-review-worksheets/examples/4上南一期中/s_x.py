def mul1(a, b):
    """四位數×一位數的直式格"""
    return VG(5, [dict(carry=True), dict(d=str(a)), dict(op="×", d=str(b), line=True), dict()], h=0.6)


def mul2(a, b, n):
    """乘以二位數的直式格（兩列＋相加）"""
    return VG(n, [dict(carry=True), dict(d=str(a)), dict(op="×", d=str(b), line=True), dict(),
                  dict(op="＋", start=1, line=True), dict()], h=0.6)


def app(text, unit):
    """應用題標題（放在直式格上面）"""
    return [text, "\n算式：（　）×（　）＝（　　）", f"\n答：＿＿＿{unit}"]


