def rot(pts, deg, dx=0, dy=0, s=1.0):
    cx = sum(p[0] for p in pts) / 3; cy = sum(p[1] for p in pts) / 3
    a = math.radians(deg)
    return [((x - cx) * s * math.cos(a) - (y - cy) * s * math.sin(a) + cx + dx,
             (x - cx) * s * math.sin(a) + (y - cy) * s * math.cos(a) + cy + dy) for x, y in pts]


