def LD(divisor, dividend, blank=7, h=0.72, sz=18):
    return lambda c: ldiv(divisor, dividend, blank=blank, h=h, size=sz, cw=0.95 if sz == 18 else 0.8, parent=c)


def VG(n, rows, h=0.7):
    return lambda c: vgrid(n, rows, h=h, parent=c)


def checkdiv(a, b, qq, r=0):
    check(b * qq + r == a and 0 <= r < b, f"{a}÷{b}")


