def divs(start, items, labels=None):
    """除法直式兩題並排（作業用 14 號字）；空白列＝商的位數×2；自動驗算並回傳 (商, 餘數)"""
    out = []
    for k in range(0, len(items), 2):
        row = []
        for j, (a, b) in enumerate(items[k:k + 2]):
            qq, r = divmod(a, b)
            checkdiv(a, b, qq, r)
            out.append((qq, r))
            n = start + k + j
            head = f"{n}. {a}÷{b}＝（　　）" + ("…（　）" if r else "")
            parts = [head] + ([labels[k + j]] if labels and labels[k + j] else [])
            row.append((parts, LD(str(b), str(a), blank=2 * len(str(qq)), h=0.62, sz=14)))
        side(row)
    return out


